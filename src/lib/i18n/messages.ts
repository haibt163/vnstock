export type MessageKey = keyof typeof vi;

const DICT: Record<Locale, Record<MessageKey, string>> = { vi, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[locale][key] ?? DICT.vi[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function sectorLabel(locale: Locale, sector: string): string {
  const key = `sector.${sector}` as MessageKey;
  if (key in DICT[locale]) return DICT[locale][key];
  return sector;
}

export function companyName(row: { name: string; nameVi: string }, locale: Locale): string {
  return locale === "vi" ? row.nameVi : row.name;
}
